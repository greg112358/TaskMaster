  The grocery words the board knows out of the box.

  Written as an explicit list of strings rather than `~w`, because `~w` splits on
  an escaped space as readily as a real one: `~w(hot\\ dog)` yields
  `["hot", "dog"]`, not `["hot dog"]`. Every multi-word term here was being
  shredded into fragments, and fragments like "hot" and "ice" then matched far
  more than they should.

  These are only **seed data**: migration 5 copies them into the `grocery_terms`
  table, and from then on `Taskmaster.Grocery.Dictionary` is the single source of
  truth. That is deliberate — a term nobody can delete would be indistinguishable
  from a bug once the family can edit the rest of the list.

  Editing this list therefore has no effect on an existing database. To change
  what a running board knows, edit the dictionary through the Groceries screen.
  """

