  @doc """
  Every built-in term as `{name, category}`, lowercased and deduplicated.
  """
  def all do
    for {terms, category} <- [{@meat_dairy, "meat_dairy"}, {@produce, "produce"}],
        term <- terms do
      {String.downcase(term), category}
    end
    # A word appearing in both lists keeps its first (meat & dairy) category,
    # matching how the old cond-based categoriser resolved the overlap.
    |> Enum.uniq_by(&elem(&1, 0))
  end
